#!/usr/bin/env python3
"""
Write tests/vectors.json: the dealing test vectors the contract and the site share.

    python scripts/gen_vectors.py            # write
    python scripts/gen_vectors.py --check    # fail if the file is not what the contract's deal() produces

deal() in contracts/doorman.py is the only definition of dealing. The browser's
copy (web/lib/deal.mjs) is held to this file by tests/test_static.py and by
web/scripts/check-deal.mjs, so the two can never drift apart unnoticed.
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tests"))

from harness import load  # noqa: E402
import genvm_double as D  # noqa: E402

OUT = ROOT / "tests" / "vectors.json"

ADDRESSES = [
    "0x" + "00" * 20,
    "0x9c4e0000000000000000000000000000000b207",
    "0x" + "a1" * 20,
    "0x" + "a2" * 20,
    "0xAbCdEf0123456789aBcDeF0123456789AbCdEf01",
    "0x" + "ff" * 20,
]
# the second is not 40 hex characters long; fix it to a real one below
ADDRESSES[1] = "0x9c4e" + "0" * 30 + "b207"
SIZES = [6, 8, 13, 20]


def build() -> list[dict]:
    mod = load(D.GL())
    out = []
    for gate in (1, 7, 123456):
        for who in ADDRESSES:
            for attempt in (1, 2, 3, 4):
                for size in SIZES:
                    out.append(
                        {
                            "gate": gate,
                            "address": who,
                            "attempt": attempt,
                            "bank": size,
                            "dealt": mod.deal(gate, who, attempt, size),
                        }
                    )
    return out


def main() -> int:
    document = {
        "about": "Dealing vectors from contracts/doorman.py deal(). Generated by scripts/gen_vectors.py; do not edit by hand.",
        "rule": "h = sha256(\"gate|address-lowercase|attempt\"); order = bank indexes sorted by sha256(h + index as 2 big-endian bytes); first three.",
        "vectors": build(),
    }
    text = json.dumps(document, indent=1) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("tests/vectors.json is not what the contract's deal() produces; run: python scripts/gen_vectors.py")
            return 1
        print(f"tests/vectors.json ok ({len(document['vectors'])} vectors)")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote tests/vectors.json ({len(document['vectors'])} vectors)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
